package com.esprit.animal.entities;

public class AnimalCareAdvice {

    private String exerciseRecommendation;
    private String dietRecommendation;
    private String environmentRecommendation;
    private String groomingRecommendation;
    private String trainingRecommendation;

    public String getExerciseRecommendation() {
        return exerciseRecommendation;
    }

    public void setExerciseRecommendation(String exerciseRecommendation) {
        this.exerciseRecommendation = exerciseRecommendation;
    }

    public String getDietRecommendation() {
        return dietRecommendation;
    }

    public void setDietRecommendation(String dietRecommendation) {
        this.dietRecommendation = dietRecommendation;
    }

    public String getEnvironmentRecommendation() {
        return environmentRecommendation;
    }

    public void setEnvironmentRecommendation(String environmentRecommendation) {
        this.environmentRecommendation = environmentRecommendation;
    }

    public String getGroomingRecommendation() {
        return groomingRecommendation;
    }

    public void setGroomingRecommendation(String groomingRecommendation) {
        this.groomingRecommendation = groomingRecommendation;
    }

    public String getTrainingRecommendation() {
        return trainingRecommendation;
    }

    public void setTrainingRecommendation(String trainingRecommendation) {
        this.trainingRecommendation = trainingRecommendation;
    }
}

